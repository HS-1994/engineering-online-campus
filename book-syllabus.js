  function injectBookSection(){
    const detail=document.querySelector('.catalog-detail-card');
    if(!detail || detail.querySelector('.campus-book-section')) return;
    const h=detail.querySelector('h2'); if(!h) return;
    const title=h.textContent.trim();
    const all=[...(window.CAMPUS_ACADEMIC?.core?Object.entries(window.CAMPUS_ACADEMIC.core):[]),...(window.CAMPUS_ACADEMIC?.civilExpansion||[]).map(x=>[x.id,x])];
    const item=all.find(([,x])=>x?.title===title);
    if(!item) return;
    const id=item[0]; const books=window.CAMPUS_BOOKS[id]; if(!books?.length) return;
    const section=document.createElement('section');
    section.className='academic-section campus-book-section';
    section.innerHTML='<h3>Recommended books from your SSD library</h3><div class="campus-book-note">Title-only references. No book files or web links are stored in the campus.</div><ul>'+books.map(b=>'<li>'+escapeHtml(b)+'</li>').join('')+'</ul>';
    const source=detail.querySelector('.academic-section:last-of-type');
    (source?.parentNode===detail ? detail.insertBefore(section,source) : detail.appendChild(section));
  }
  function escapeHtml(v){return String(v??'').replace(/[&<>\"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','\\':'&#92;','"':'&quot;'}[c]));}
  const s=document.createElement('style'); s.textContent='.campus-book-note{font-size:.75rem;color:#879bae;margin:4px 0 8px}.campus-book-section li{margin-bottom:4px}'; document.head.appendChild(s);
  const obs=new MutationObserver(injectBookSection); obs.observe(document.body,{childList:true,subtree:true});
  injectBookSection();
